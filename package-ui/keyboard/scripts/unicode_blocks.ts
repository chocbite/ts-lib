//Generates ../unicode_blocks.ts and ../unicode_emoji.ts, the Unicode blocks and emoji of the character picker of the keyboard, see ../INTERNAL.md
//Run from the repo root with: node package-ui/keyboard/scripts/unicode_blocks.ts
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const VERSION = "17.0.0";
const BLOCKS = `https://www.unicode.org/Public/${VERSION}/ucd/Blocks.txt`;
const EMOJI = `https://www.unicode.org/Public/${VERSION}/emoji/emoji-test.txt`;
const LICENSE = "https://www.unicode.org/license.txt";
const FOLDER = dirname(fileURLToPath(import.meta.url));
const OUTPUT = join(FOLDER, "../unicode_blocks.ts");
const OUTPUT_EMOJI = join(FOLDER, "../unicode_emoji.ts");
//The emoji of the skin tones, the variants with them are left out, every hand and person would be there 5 more times
const SKIN_TONE = /[\u{1F3FB}-\u{1F3FF}]/u;
//The group of the parts of emoji, skin tones and hair, which are not picked alone
const COMPONENT_GROUP = "Component";

//Blocks that are left out, characters that are not typed alone, or too many to page through,
//CJK ideographs, Hangul syllables and the large historic scripts need an input method
const EXCLUDED =
  /Surrogates|Private Use|Variation Selectors|^Tags$|^Specials$|^CJK Unified Ideographs|^Hangul Syllables$|^Yi Syllables$|^Tangut|^Khitan Small Script$|^Nushu$|^Egyptian Hieroglyph|^Cuneiform|^Anatolian Hieroglyphs$|^Bamum Supplement$/;

//Characters that are not typed, control, format, surrogate, private use and unassigned
const NOT_TYPED = /\p{C}/u;
//Characters of a script, not shared by all scripts like symbols, punctuation and digits
const OF_SCRIPT = /[^\p{Script=Common}\p{Script=Inherited}]/u;

async function get(url: string): Promise<string> {
  for (let attempt = 0; ; attempt++) {
    const response = await fetch(url);
    if (response.ok) return response.text();
    if (attempt === 3) throw new Error(`${response.status} for ${url}`);
    await new Promise((resolve) => setTimeout(resolve, 1000 * (attempt + 1)));
  }
}

interface Block {
  name: string;
  start: number;
  end: number;
  /**Mostly characters of one script, otherwise symbols*/
  script: boolean;
}

const blocks: Block[] = [];
for (const line of (await get(BLOCKS)).split("\n")) {
  const match = /^([0-9A-F]+)\.\.([0-9A-F]+);\s*(.+?)\s*$/.exec(line);
  if (!match || EXCLUDED.test(match[3])) continue;
  const start = parseInt(match[1], 16);
  const end = parseInt(match[2], 16);
  let typed = 0;
  let of_script = 0;
  for (let code = start; code <= end; code++) {
    const char = String.fromCodePoint(code);
    if (NOT_TYPED.test(char)) continue;
    typed++;
    if (OF_SCRIPT.test(char)) of_script++;
  }
  if (typed === 0) continue;
  blocks.push({ name: match[3], start, end, script: of_script * 2 > typed });
}

const license = await get(LICENSE);
const code = `//Generated by scripts/unicode_blocks.ts from Blocks.txt of Unicode ${VERSION}, do not edit, see INTERNAL.md
/*
${license.trim().replace(/\*\//g, "* /")}
*/

/**The Unicode blocks of the character picker, name, first and last code point, and 1 for a script, mostly characters of one script, or 0 for symbols
 * Blocks of characters that are not typed alone, or too many to page through, like the CJK ideographs, are left out*/
export const UNICODE_BLOCKS: readonly (readonly [
  name: string,
  start: number,
  end: number,
  script: 0 | 1,
])[] = [
${blocks.map((b) => `  [${JSON.stringify(b.name)}, 0x${b.start.toString(16)}, 0x${b.end.toString(16)}, ${b.script ? 1 : 0}],`).join("\n")}
];
`;
writeFileSync(OUTPUT, code);
console.log(
  `Wrote ${blocks.length} blocks to ${OUTPUT}, ${blocks.filter((b) => b.script).length} scripts, ${blocks.filter((b) => !b.script).length} symbols`,
);

//      ______ __  __  ____       _ _____
//     |  ____|  \/  |/ __ \     | |_   _|
//     | |__  | \  / | |  | |    | | | |
//     |  __| | |\/| | |  | |_   | | | |
//     | |____| |  | | |__| | |__| |_| |_
//     |______|_|  |_|\____/ \____/|_____|
//The fully qualified emoji in the order and groups of Unicode, a sequence of code points is one emoji
interface Group {
  name: string;
  subgroups: { name: string; emoji: string[] }[];
}
const groups: Group[] = [];
for (const line of (await get(EMOJI)).split("\n")) {
  const group = /^# group: (.+)$/.exec(line);
  if (group) {
    groups.push({ name: group[1].trim(), subgroups: [] });
    continue;
  }
  const subgroup = /^# subgroup: (.+)$/.exec(line);
  if (subgroup) {
    groups.at(-1)!.subgroups.push({ name: subgroup[1].trim(), emoji: [] });
    continue;
  }
  const entry = /^([0-9A-F ]+?)\s*; fully-qualified\s*#/.exec(line);
  if (!entry) continue;
  const emoji = String.fromCodePoint(
    ...entry[1].split(" ").map((c) => parseInt(c, 16)),
  );
  if (SKIN_TONE.test(emoji)) continue;
  groups.at(-1)!.subgroups.at(-1)!.emoji.push(emoji);
}
const picked = groups
  .filter((g) => g.name !== COMPONENT_GROUP)
  .map((g) => ({ ...g, subgroups: g.subgroups.filter((s) => s.emoji.length) }))
  .filter((g) => g.subgroups.length);
for (const g of picked)
  for (const sub of g.subgroups)
    if (sub.emoji.some((e) => e.includes(" ")))
      throw new Error(`An emoji of ${sub.name} has a space, the separator`);

const emoji_code = `//Generated by scripts/unicode_blocks.ts from emoji-test.txt of Unicode ${VERSION}, do not edit, see INTERNAL.md
/*
${license.trim().replace(/\*\//g, "* /")}
*/

/**The emoji of the character picker in the groups and subgroups of Unicode, in its order,
 * the emoji of a subgroup are one string separated by spaces, an emoji can be several code points, like a flag
 * The variants with a skin tone are left out*/
export const UNICODE_EMOJI: readonly (readonly [
  group: string,
  subgroups: readonly (readonly [name: string, emoji: string])[],
])[] = [
${picked
  .map(
    (g) =>
      `  [${JSON.stringify(g.name)}, [\n${g.subgroups
        .map(
          (sub) =>
            `    [${JSON.stringify(sub.name)}, ${JSON.stringify(sub.emoji.join(" "))}],`,
        )
        .join("\n")}\n  ]],`,
  )
  .join("\n")}
];
`;
writeFileSync(OUTPUT_EMOJI, emoji_code);
console.log(
  `Wrote ${picked.reduce((n, g) => n + g.subgroups.reduce((m, sub) => m + sub.emoji.length, 0), 0)} emoji in ${picked.length} groups and ${picked.reduce((n, g) => n + g.subgroups.length, 0)} subgroups to ${OUTPUT_EMOJI}`,
);
